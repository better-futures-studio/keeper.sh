const aclSetuserArgs = (
  username: string,
  password: string,
  database: number,
  channelPattern: string,
): string[] => [
  username,
  "reset",
  "on",
  `>${password}`,
  "~*",
  "resetchannels",
  `&${channelPattern}`,
  `db=${String(database)}`,
  "-@all",
  ...KEEPER_ACL_COMMANDS.map((command) => `+${command}`),
];

const keeperAclSetuserArgs = (): string[] =>
  aclSetuserArgs(
    KEEPER_USERNAME,
    SYNTHETIC_KEEPER_PASSWORD,
    KEEPER_DATABASE,
    KEEPER_CHANNEL_PATTERN,
  );

